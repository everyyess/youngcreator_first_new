/** 본문 내용에 포함된 기준 태그들만 추출해 프롬프트 힌트로 주입 (토큰 절약 및 속도 향상) */
export function buildDynamicTagListHint(title: string, content: string): string {
  const haystack = (String(title ?? "") + " " + String(content ?? "")).toLowerCase().replace(/\s+/g, "");
  
  // 소문자 및 공백 제거 기준으로 비교하여 포함 여부 판단
  const matchedTopics = CANONICAL_TOPICS.filter((t) => haystack.includes(t.toLowerCase().replace(/\s+/g, "")));
  const matchedCompanies = CANONICAL_COMPANIES.filter((c) => haystack.includes(c.toLowerCase().replace(/\s+/g, "")));
  const matchedMacro = CANONICAL_MACRO.filter((m) => haystack.includes(m.toLowerCase().replace(/\s+/g, "")));
  
  return `기준 Topic 태그 목록: ${matchedTopics.join(", ")}\n기준 Company 태그 목록: ${matchedCompanies.join(", ")}\n기준 Macro 태그 목록: ${matchedMacro.join(", ")}`;
}


