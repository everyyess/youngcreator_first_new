/** 비교용 키: 소문자화 + 공백 제거 (A-3/A-4 띄어쓰기 없는 버전 매칭) */
function normKey(s: string): string {
  return s.toLowerCase().replace(/\s+/g, "");
}

/** A-5/A-6/A-11/A-12: 표기 형식 정리 — #제거, ($티커)/괄호 티커 제거, "한글명(약어)" → 약어 판단은 매핑에 위임 */
function cleanFormat(raw: string): string {
  let s = raw.trim();
  s = s.replace(/^#+/, "");                      // A-12 해시태그 제거
  s = s.replace(/\(\$?[A-Z]{1,6}\)\s*$/i, "");   // A-6 뒤에 붙은 (티커)/($티커) 제거
  s = s.replace(/\s{2,}/g, " ").trim();
  return s;
}

function resolve(
  raw: string,
  synonyms: Record<string, string>,
  canonicalByKey: Map<string, string>,
  excludeByKey?: Map<string, string>,
): string | null {
  const cleaned = cleanFormat(raw);
  if (!cleaned) return null;
  const key = normKey(cleaned);
  if (BLOCKED_TAG_KEYS.has(key)) return null;

  let resolved: string;
  // 1) 동의어 매핑 우선
  if (synonyms[key]) {
    resolved = synonyms[key];
  } else {
    // 2) 기준 목록과 일치 (대소문자·공백 무시)
    const canonical = canonicalByKey.get(key);
    if (canonical) {
      resolved = canonical;
    } else {
      // 3) 기준 목록에 없으면 신규 태그로 유지 — 단 B-1/B-2 문장형·구조용 태그는 폐기한다
      //    (15자 초과, 문장부호 포함, 또는 띄어쓰기 포함 시 문장/구절로 보고 통째로 버림 —
      //    공백만 지우고 살리면 "실적 분석"→"실적분석" 같은 저품질 신규 태그가 계속 쌓이므로
      //    A-3/A-4 띄어쓰기 없는 표기 규칙은 기준 목록·동의어 일치분에만 적용하고 자유입력에는 적용하지 않는다)
      if (cleaned.length > 15 || /[.,!?"'…]/.test(cleaned) || /\s/.test(cleaned)) return null;
      resolved = cleaned;
    }
  }

  const resolvedKey = normKey(resolved);
  if (BLOCKED_TAG_KEYS.has(resolvedKey)) return null;
  // 다른 카테고리의 기준 태그와 정확히 일치하면 이 카테고리에는 남기지 않는다
  if (excludeByKey?.has(resolvedKey)) return null;
  return resolved;
}

/** Topic 태그 배열 정규화: 동의어 통일 + 형식 정리 + 중복 제거 */
export function normalizeTopics(tags: string[]): string[] {
  const out: string[] = [];
  for (const t of tags) {
    const r = resolve(String(t ?? ""), TOPIC_SYNONYMS, canonicalTopicByKey, macroOrCompanyByKey);
    if (r && !out.includes(r)) out.push(r);
  }
  return out;
}

/** Macro 태그 배열 정규화: 동의어 통일 + 형식 정리 + 중복 제거 */
export function normalizeMacro(tags: string[]): string[] {
  const out: string[] = [];
  for (const t of tags) {
    const r = resolve(String(t ?? ""), MACRO_SYNONYMS, canonicalMacroByKey, topicOrCompanyByKey);
    if (r && !out.includes(r)) out.push(r);
  }

  // CPI가 포함되면 물가도 자동 추가
  if (out.includes("CPI") && !out.includes("물가")) {
    out.push("물가");
  }
  // 달러가 포함되면 환율도 자동 추가
  if (out.includes("달러") && !out.includes("환율")) {
    out.push("환율");
  }

  return out;
}

/** Company 태그 배열 정규화: 동의어 통일 + 형식 정리 + 중복 제거 + D-4(SK 지주사) 처리 */
export function normalizeCompanies(tags: string[]): string[] {
  const out: string[] = [];
  for (const t of tags) {
    const r = resolve(String(t ?? ""), COMPANY_SYNONYMS, canonicalCompanyByKey, topicOrMacroByKey);
    if (r && !out.includes(r)) out.push(r);
  }
  // D-4: SK 계열사 태그가 함께 있으면 지주사 'SK' 제거
  const skAffiliates = ["SK하이닉스", "SK이노베이션", "SK텔레콤", "SK가스", "SKC"];
  if (out.includes("SK") && out.some((c) => skAffiliates.includes(c))) {
    return out.filter((c) => c !== "SK");
  }
  return out;
}

function containsTagMention(text: string, candidate: string): boolean {
  const compactText = text.toLowerCase().replace(/[^0-9a-z가-힣]/g, "");
  const compactCandidate = candidate.toLowerCase().replace(/[^0-9a-z가-힣]/g, "");
  if (!compactCandidate) return false;

  if (/^[가-힣]$/.test(candidate)) {
    const escaped = candidate.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&");
    return new RegExp(`(^|[^0-9a-z가-힣])${escaped}([^0-9a-z가-힣]|$)`, "i").test(text);
  }
  if (/^[a-z0-9]+$/i.test(candidate) && compactCandidate.length <= 3) {
    const escaped = candidate.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&");
    return new RegExp(`(^|[^a-z0-9])${escaped}([^a-z0-9]|$)`, "i").test(text);
  }
  return compactText.includes(compactCandidate);
}

function mentionedTags(
  text: string,
  canonical: readonly string[],
  synonyms: Record<string, string>,
): string[] {
  return [
    ...canonical.filter((tag) => containsTagMention(text, tag)),
    ...Object.keys(synonyms).filter((tag) => containsTagMention(text, tag)),
  ];
}

/**
 * AI 태그가 아직 저장되지 않은 목록/레거시 행을 위한 결정적 폴백 추출.
 * 기준 태그뿐 아니라 동의어 키도 함께 탐색한 뒤 기존 정규화 규칙을 그대로 적용한다.
 */
export function extractMappedTags(text: string): {
  topics: string[];
  companies: string[];
  macro: string[];
} {
  return {
    topics: normalizeTopics(mentionedTags(text, CANONICAL_TOPICS, TOPIC_SYNONYMS)),
    companies: normalizeCompanies(mentionedTags(text, CANONICAL_COMPANIES, COMPANY_SYNONYMS)),
    macro: normalizeMacro(mentionedTags(text, CANONICAL_MACRO, MACRO_SYNONYMS)),
  };
}

